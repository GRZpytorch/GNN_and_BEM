def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Evaluate the trained full-graph attention model "
            "and reconstruct the interior field using BEM."
        )
    )

    parser.add_argument(
        "--data_dir",
        type=Path,
        default=Path(
            DEFAULT_CONFIG["data_dir"]
        ),
    )

    parser.add_argument(
        "--case",
        type=str,
        choices=[
            "case1",
            "case2",
            "case3",
        ],
        default=DEFAULT_CONFIG["case"],
    )

    parser.add_argument(
        "--ckpt",
        type=Path,
        default=Path(
            DEFAULT_CONFIG["ckpt"]
        ),
    )

    parser.add_argument(
        "--out_dir",
        type=Path,
        default=Path(
            DEFAULT_CONFIG["out_dir"]
        ),
    )

    parser.add_argument(
        "--sample_idx",
        type=int,
        default=DEFAULT_CONFIG["sample_idx"],
    )

    parser.add_argument(
        "--quad_res",
        type=int,
        default=DEFAULT_CONFIG["quad_res"],
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    run_test(
        data_dir=args.data_dir,
        case=args.case,
        ckpt_path=args.ckpt,
        out_dir=args.out_dir,
        sample_idx=args.sample_idx,
        quad_res=args.quad_res,
    )


if __name__ == "__main__":
    main()
