def _build_forced_ticks(
    start: float,
    step: float,
    count: int,
) -> np.ndarray:
    if count <= 0:
        raise ValueError("count must be greater than zero")

    return (
        start
        + step
        * np.arange(count, dtype=np.float64)
    )


def _apply_forced_ticks(
    ax: mpl.axes.Axes,
    case: str | None,
) -> None:
    if case is None:
        return

    cfg = AXIS_TICK_CFG.get(
        case,
        {"enable": False},
    )

    if not cfg.get("enable", False):
        return

    xticks = _build_forced_ticks(
        cfg["x_start"],
        cfg["x_step"],
        cfg["x_count"],
    )

    yticks = _build_forced_ticks(
        cfg["y_start"],
        cfg["y_step"],
        cfg["y_count"],
    )

    xlabels = [
        cfg["label_fmt"].format(value)
        for value in xticks
    ]

    ylabels = [
        cfg["label_fmt"].format(value)
        for value in yticks
    ]

    ax.xaxis.set_major_locator(
        FixedLocator(xticks)
    )

    ax.yaxis.set_major_locator(
        FixedLocator(yticks)
    )

    ax.xaxis.set_major_formatter(
        FixedFormatter(xlabels)
    )

    ax.yaxis.set_major_formatter(
        FixedFormatter(ylabels)
    )

    ax.set_xlim(*cfg["xlim"])
    ax.set_ylim(*cfg["ylim"])
    ax.minorticks_off()


def _apply_axis_style(
    ax: mpl.axes.Axes,
    case: str | None = None,
) -> None:
    ax.set_xlabel(
        PLOT_CFG["x_label"],
        fontsize=PLOT_CFG["label_fontsize"],
        fontstyle="italic",
    )

    ax.set_ylabel(
        PLOT_CFG["y_label"],
        fontsize=PLOT_CFG["label_fontsize"],
        fontstyle="italic",
    )

    ax.tick_params(
        axis="both",
        labelsize=PLOT_CFG["tick_labelsize"],
        width=PLOT_CFG["axis_linewidth"],
    )

    for spine in ax.spines.values():
        spine.set_linewidth(
            PLOT_CFG["axis_linewidth"]
        )

    if PLOT_CFG["show_grid"]:
        ax.grid(
            True,
            alpha=PLOT_CFG["grid_alpha"],
        )

    _apply_forced_ticks(
        ax,
        case,
    )


def _make_legend(
    ax: mpl.axes.Axes,
    label: str | None = None,
    add_unknown: bool = False,
    legend_loc: str = "upper right",
) -> None:
    if not PLOT_CFG.get("show_legend", True):
        return

    handles: list[Line2D] = []

    if label is not None:
        handles.append(
            Line2D(
                [0],
                [0],
                marker="o",
                color="w",
                label=label,
                markerfacecolor="gray",
                markeredgecolor=PLOT_CFG["known_edgecolor"],
                markersize=6,
            )
        )

    if add_unknown:
        handles.append(
            Line2D(
                [0],
                [0],
                marker="x",
                color=PLOT_CFG["unknown_color"],
                label=PLOT_CFG["unknown_label"],
                linestyle="None",
                markersize=7,
                markeredgewidth=1.2,
            )
        )

    if handles:
        ax.legend(
            handles=handles,
            loc=legend_loc,
            fontsize=PLOT_CFG["legend_fontsize"],
            frameon=True,
        )


def _add_colorbar(
    fig: mpl.figure.Figure,
    ax: mpl.axes.Axes,
    artist: Any,
    fmt: str | None = None,
):
    vmin, vmax = artist.get_clim()

    n_ticks = int(
        PLOT_CFG.get("colorbar_n_ticks", 7)
    )

    if np.isclose(vmin, vmax):
        ticks = [vmin]
    else:
        ticks = np.linspace(
            vmin,
            vmax,
            n_ticks,
        )

    colorbar = fig.colorbar(
        artist,
        ax=ax,
        fraction=PLOT_CFG["colorbar_fraction"],
        pad=PLOT_CFG["colorbar_pad"],
        shrink=PLOT_CFG["colorbar_shrink"],
        aspect=PLOT_CFG["colorbar_aspect"],
        format=fmt,
        ticks=ticks,
    )

    colorbar.ax.tick_params(
        labelsize=PLOT_CFG["colorbar_ticksize"]
    )

    return colorbar


