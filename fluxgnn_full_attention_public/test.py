def build_problem_from_params(
    case: str,
    params: np.ndarray,
) -> Callable[[np.ndarray], np.ndarray]:
    """
    Construct the source-term function for the selected problem.
    """
    params = np.asarray(params, dtype=np.float64).reshape(-1)

    if case == "case1":
        # Case 1 is the Laplace equation:
        #     -Delta u = 0.
        def f_fn(x: np.ndarray) -> np.ndarray:
            x = np.asarray(x)

            return np.zeros(
                (x.shape[0],),
                dtype=np.float64,
            )

        return f_fn

    if case == "case2":
        if params.size < 3:
            raise ValueError(
                "case2 requires at least three parameters: [a, b, c]"
            )

        a, b, c = [float(v) for v in params[:3]]

        def f_fn(x: np.ndarray) -> np.ndarray:
            x = np.asarray(x, dtype=np.float64)

            xx = x[:, 0]
            yy = x[:, 1]

            return (
                4.0 * a
                + 8.0 * b * xx
                + 8.0 * c * yy
            )

        return f_fn

    if case == "case3":
        if params.size < 3:
            raise ValueError(
                "case3 requires at least three parameters: [A, m, n]"
            )

        amplitude = float(params[0])
        frequency_m = int(round(float(params[1])))
        frequency_n = int(round(float(params[2])))

        def f_fn(x: np.ndarray) -> np.ndarray:
            x = np.asarray(x, dtype=np.float64)

            xx = x[:, 0]
            yy = x[:, 1]

            factor = (
                amplitude
                * np.pi**2
                * (
                    frequency_m**2
                    + frequency_n**2
                )
            )

            return (
                factor
                * np.sin(frequency_m * np.pi * xx)
                * np.sin(frequency_n * np.pi * yy)
            )

        return f_fn

    raise ValueError(
        f"Unknown case '{case}'. "
        "Expected one of: case1, case2, case3"
    )


