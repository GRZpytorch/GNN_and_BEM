def compute_error_metrics(
    prediction: np.ndarray,
    reference: np.ndarray,
) -> dict[str, float]:
    """
    Compute common regression error metrics.
    """
    prediction = np.asarray(
        prediction,
        dtype=np.float64,
    ).reshape(-1)

    reference = np.asarray(
        reference,
        dtype=np.float64,
    ).reshape(-1)

    _validate_same_shape(
        "prediction",
        prediction,
        "reference",
        reference,
    )

    valid = (
        np.isfinite(prediction)
        & np.isfinite(reference)
    )

    if not np.any(valid):
        raise ValueError(
            "No finite prediction-reference pairs are available"
        )

    prediction_valid = prediction[valid]
    reference_valid = reference[valid]

    error = prediction_valid - reference_valid

    mse = float(np.mean(error**2))
    rmse = float(np.sqrt(mse))
    mae = float(np.mean(np.abs(error)))
    max_abs = float(np.max(np.abs(error)))

    reference_norm = float(
        np.linalg.norm(reference_valid)
    )

    error_norm = float(
        np.linalg.norm(error)
    )

    if reference_norm > 1e-14:
        relative_l2 = error_norm / reference_norm
    else:
        relative_l2 = float("nan")

    reference_range = float(
        np.max(reference_valid)
        - np.min(reference_valid)
    )

    if reference_range > 1e-14:
        normalized_max_abs = max_abs / reference_range
    else:
        normalized_max_abs = float("nan")

    return {
        "mse": mse,
        "rmse": rmse,
        "mae": mae,
        "max_abs": max_abs,
        "relative_l2": float(relative_l2),
        "normalized_max_abs": float(normalized_max_abs),
    }


