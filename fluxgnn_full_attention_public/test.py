def _to_numpy(
    value: Any,
    *,
    dtype: np.dtype | type | None = None,
    flatten: bool = False,
) -> np.ndarray:
    """
    Convert a PyTorch tensor or array-like object to a NumPy array.
    """
    if isinstance(value, torch.Tensor):
        array = value.detach().cpu().numpy()
    else:
        array = np.asarray(value)

    if dtype is not None:
        array = array.astype(dtype, copy=False)

    if flatten:
        array = array.reshape(-1)

    return array


def _check_finite(
    name: str,
    array: np.ndarray,
    *,
    allow_nan: bool = False,
) -> None:
    """
    Validate that an array does not contain invalid numerical values.
    """
    array = np.asarray(array)

    if allow_nan:
        if np.any(np.isinf(array)):
            raise FloatingPointError(
                f"{name} contains infinite values"
            )
    else:
        if not np.all(np.isfinite(array)):
            raise FloatingPointError(
                f"{name} contains NaN or infinite values"
            )


def _validate_same_shape(
    name_a: str,
    array_a: np.ndarray,
    name_b: str,
    array_b: np.ndarray,
) -> None:
    if array_a.shape != array_b.shape:
        raise ValueError(
            f"{name_a} shape {array_a.shape} does not match "
            f"{name_b} shape {array_b.shape}"
        )


def _finite_minmax(
    *arrays: np.ndarray,
    padding: float = 1e-8,
) -> tuple[float, float]:
    """
    Return a common finite minimum and maximum for multiple arrays.
    """
    finite_parts: list[np.ndarray] = []

    for array in arrays:
        values = np.asarray(array, dtype=np.float64)
        finite_values = values[np.isfinite(values)]

        if finite_values.size > 0:
            finite_parts.append(finite_values)

    if not finite_parts:
        raise ValueError(
            "Cannot determine a color range from empty or non-finite arrays"
        )

    combined = np.concatenate(finite_parts)

    vmin = float(np.min(combined))
    vmax = float(np.max(combined))

    if np.isclose(vmin, vmax):
        scale = max(abs(vmin), 1.0)
        delta = max(padding, padding * scale)

        vmin -= delta
        vmax += delta

    return vmin, vmax


def _symmetric_limit(
    array: np.ndarray,
    *,
    minimum: float = 1e-12,
) -> float:
    """
    Return a positive symmetric color limit around zero.
    """
    values = np.asarray(array, dtype=np.float64)
    finite_values = values[np.isfinite(values)]

    if finite_values.size == 0:
        return minimum

    limit = float(np.max(np.abs(finite_values)))

    if not np.isfinite(limit) or limit < minimum:
        limit = minimum

    return limit


def _validate_node_array(
    name: str,
    array: np.ndarray,
    num_nodes: int,
) -> np.ndarray:
    """
    Flatten and validate a node-wise array.
    """
    array = np.asarray(array, dtype=np.float64).reshape(-1)

    if array.shape[0] != num_nodes:
        raise ValueError(
            f"{name} contains {array.shape[0]} values, "
            f"but the boundary has {num_nodes} nodes"
        )

    _check_finite(name, array)

    return array


