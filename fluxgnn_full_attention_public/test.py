def _boundary_edge_masks(
    coords_np: np.ndarray,
    tol: float = 1e-8,
) -> dict[str, np.ndarray]:
    coords_np = np.asarray(
        coords_np,
        dtype=np.float64,
    )

    if coords_np.ndim != 2 or coords_np.shape[1] != 2:
        raise ValueError(
            "Boundary coordinates must have shape [N, 2]"
        )

    x = coords_np[:, 0]
    y = coords_np[:, 1]

    x_min = float(np.min(x))
    x_max = float(np.max(x))
    y_min = float(np.min(y))
    y_max = float(np.max(y))

    left = np.abs(x - x_min) < tol
    right = np.abs(x - x_max) < tol
    bottom = np.abs(y - y_min) < tol
    top = np.abs(y - y_max) < tol

    return {
        "left": left,
        "right": right,
        "top": top,
        "bottom": bottom,
        "left_right": left | right,
        "top_bottom": top | bottom,
        "all_boundary": (
            left
            | right
            | top
            | bottom
        ),
    }


def build_custom_masks(
    boundary_coords: np.ndarray,
    q_err: np.ndarray | None = None,
    u_err_grid: np.ndarray | None = None,
) -> dict[str, np.ndarray]:
    custom_masks: dict[str, np.ndarray] = {}

    # Examples:
    #
    # custom_masks["left_half"] = (
    #     boundary_coords[:, 0] < 0.5
    # )
    #
    # if q_err is not None:
    #     custom_masks["positive_q_error"] = q_err > 0.0
    #
    # if u_err_grid is not None:
    #     custom_masks["large_u_region"] = (
    #         np.abs(u_err_grid) > 0.05
    #     )

    return custom_masks


def build_boundary_x_mask(
    mode: str | None,
    boundary_coords: np.ndarray,
    q_err: np.ndarray | None = None,
) -> np.ndarray | None:
    if mode is None or mode == "none":
        return None

    edges = _boundary_edge_masks(
        boundary_coords
    )

    custom = build_custom_masks(
        boundary_coords,
        q_err=q_err,
        u_err_grid=None,
    )

    if mode in edges:
        return edges[mode]

    if mode == "large_q_error":
        if q_err is None:
            raise ValueError(
                "large_q_error mode requires q_err"
            )

        return (
            np.abs(q_err)
            > X_CFG["large_error_threshold_q"]
        )

    if mode in custom:
        return custom[mode]

    raise ValueError(
        f"Unknown boundary x_mode: {mode}"
    )


def build_grid_x_mask(
    mode: str | None,
    boundary_coords: np.ndarray,
    u_err_grid: np.ndarray | None = None,
) -> np.ndarray | None:
    if mode is None or mode == "none":
        return None

    custom = build_custom_masks(
        boundary_coords,
        q_err=None,
        u_err_grid=u_err_grid,
    )

    if mode == "large_u_error":
        if u_err_grid is None:
            raise ValueError(
                "large_u_error mode requires u_err_grid"
            )

        return (
            np.abs(u_err_grid)
            > X_CFG["large_error_threshold_u"]
        )

    if mode in custom:
        return custom[mode]

    raise ValueError(
        f"Unknown grid x_mode: {mode}"
    )


def build_interior_x_mask(
    mode: str | None,
    u_err: np.ndarray | None = None,
) -> np.ndarray | None:
    if mode is None or mode == "none":
        return None

    if mode == "large_u_error":
        if u_err is None:
            raise ValueError(
                "large_u_error mode requires u_err"
            )

        return (
            np.abs(u_err)
            > X_CFG["large_error_threshold_u"]
        )

    raise ValueError(
        f"Unknown interior x_mode: {mode}"
    )


